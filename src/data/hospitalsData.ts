// Helper to calculate approximate distance between two lat/lng coordinates in km
export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

// Generate context-aware nearby hospitals for any risk zone
export function getNearbyHospitalsForZone(
  zoneId: string,
  zoneLat: number,
  zoneLng: number,
  zoneState: string,
  zoneStatus: string
): HospitalFacility[] {
  // Sort hospitals by proximity to zone coordinates
  const sorted = [...ALL_REGIONAL_HOSPITALS]
    .map((h) => {
      const dist = calculateDistanceKm(zoneLat, zoneLng, h.lat, h.lng);
      // Rough mountainous ETA: in Northeast hills, average road speed is 25-35 km/h
      const estMinutes = Math.max(8, Math.round((dist / 32) * 60));

      let routeStatus = h.accessRouteStatus;
      // If the zone itself is ROAD AT RISK or CRITICAL and uses the same highway
      if (zoneStatus === 'ROAD AT RISK' || zoneStatus === 'CRITICAL') {
        if (zoneId === 'rz-1' && (h.id === 'hosp-rangpo' || h.id === 'hosp-singtam')) {
          routeStatus = 'Route Impaired (Caution)';
        } else if (zoneId === 'rz-2' && h.id === 'hosp-mangan') {
          routeStatus = 'Cut Off / Alternate Route Needed';
        } else if (zoneId === 'rz-4' && h.id === 'hosp-khliehriat') {
          routeStatus = 'Route Impaired (Caution)';
        } else if (zoneId === 'rz-7' && h.id === 'hosp-haflong') {
          routeStatus = 'Route Impaired (Caution)';
        }
      }

      return {
        ...h,
        distanceKm: dist,
        etaMinutes: estMinutes,
        accessRouteStatus: routeStatus,
      };
    })
    .sort((a, b) => a.distanceKm - b.distanceKm);

  // Return the closest 2 to 3 facilities (ensuring at least 1 local and 1 trauma/tertiary center)
  const closestLocal = sorted.slice(0, 2);
  const tertiary = sorted.find(
    (h) => h.type === 'Trauma & Tertiary Hospital' && !closestLocal.some((c) => c.id === h.id)
  );

  return tertiary ? [...closestLocal, tertiary] : sorted.slice(0, 3);
}
