/** Haversine distance in km. */
function kmBetween(aLat: number, aLng: number, bLat: number, bLng: number): number {
  const R = 6371;
  const dLat = ((bLat - aLat) * Math.PI) / 180;
  const dLng = ((bLng - aLng) * Math.PI) / 180;
  const s =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((aLat * Math.PI) / 180) * Math.cos((bLat * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

/** Real recorded landslides within `radiusKm` of a point. */
export function countNearbyEvents(lat: number, lng: number, radiusKm = 25): number {
  let n = 0;
  for (const e of HISTORICAL_EVENTS) {
    if (kmBetween(lat, lng, e.lat, e.lng) <= radiusKm) n++;
  }
  return n;
}
